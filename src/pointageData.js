export function getYesterdayIsoDate(referenceDate = new Date()) {
  const localDate = new Date(referenceDate);
  localDate.setHours(0, 0, 0, 0);
  localDate.setDate(localDate.getDate() - 1);

  const year = localDate.getFullYear();
  const month = String(localDate.getMonth() + 1).padStart(2, '0');
  const day = String(localDate.getDate()).padStart(2, '0');

  return `${year}-${month}-${day}`;
}

export function formatIsoDateFr(isoDate) {
  if (!isoDate) return '';

  const [year, month, day] = isoDate.split('-');
  if (!year || !month || !day) return isoDate;

  return `${day}/${month}/${year}`;
}

export function getAvailablePointageDates() {
  return Object.keys(pointageDailySnapshots).sort((a, b) => a.localeCompare(b));
}

export function resolveInitialPointageDate(preferredIsoDate) {
  const availableDates = getAvailablePointageDates();

  if (availableDates.includes(preferredIsoDate)) {
    return preferredIsoDate;
  }

  if (!availableDates.length) {
    return preferredIsoDate;
  }

  const pastOrEqualDates = availableDates.filter((date) => date <= preferredIsoDate);

  if (pastOrEqualDates.length) {
    return pastOrEqualDates[pastOrEqualDates.length - 1];
  }

  return availableDates[availableDates.length - 1];
}

