export function localizePointageDepartment(value, translate) {
  const keys = {
    administration: 'daily.departments.administration', production: 'daily.departments.production',
    maintenance: 'daily.departments.maintenance', gardiennage: 'daily.departments.guarding',
    nettoyage: 'daily.departments.cleaning', projet: 'daily.departments.project',
    'non renseigne': 'daily.departments.unknown', 'service non renseigne': 'daily.departments.unknownService',
    injection: 'production.serviceLabels.injection', metallisation: 'production.serviceLabels.metallisation',
    serigraphie: 'production.serviceLabels.serigraphie', assemblage: 'production.serviceLabels.assemblage',
  };
  return String(value || '').split(' · ').map((part) => {
    const key = part.trim().normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
    return keys[key] ? translate(keys[key]) : part;
  }).join(' · ');
}
